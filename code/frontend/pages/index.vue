    address: 'Пр-т Луначарского, д. 5',
    phone: '+7 (8202) 21-12-34',
    email: 'info@chsu.ru'
  }
]

const totalPages = computed(() =>
  Math.ceil(newsList.value.length / newsPerPage)
)

const formatDate = (d) =>
  new Date(d).toLocaleDateString('ru-RU', {
    day: '2-digit',
    month: 'long',
    year: 'numeric'
  })

async function fetchCategories() {
  try {
    const { data } = await axios.get(`${API_URL}/categories_news`)
    categories_news.value = data
  } catch (e) {
    console.error(e)
  }
}

async function fetchNews() {
  try {
    const catParam = selectedCategory.value
      ? `&category=${selectedCategory.value}`
      : ''
    const skip = (currentPage.value - 1) * newsPerPage
    const { data } = await axios.get(
      `${API_URL}/news?skip=${skip}&limit=${newsPerPage}${catParam}`
    )
    newsList.value = data
  } catch (e) {
    console.error(e)
  }
}

function selectCategory(cat) {
  selectedCategory.value = cat
  currentPage.value = 1
  fetchNews()
}

function prevPage() {
  if (currentPage.value > 1) {
    currentPage.value--
    fetchNews()
  }
}

function nextPage() {
  if (currentPage.value < totalPages.value) {
    currentPage.value++
    fetchNews()
  }
}

onMounted(() => {
  fetchCategories()
  fetchNews()
  fetchPaintings()
  fetchGraphics()
  fetchBooksHome()
})
</script>

