const paintingItems = ref([])

const graphicsItems = ref([])

const bookItems = ref([])

import chermo from '@/assets/img/landing/img/chermo.png'
import chsu from '@/assets/img/landing/img/chsu.png'

const API_URL = 'http://localhost:8000'
const categories_news = ref([])
const newsList = ref([])
const selectedCategory = ref(null)
const currentPage = ref(1)
const newsPerPage = 6

async function fetchPaintings() {
  try {
    const { data } = await axios.get(`${API_URL}/api/v1/art-items`, {
      params: { category: 1 }
    })
    paintingItems.value = data.results.map(a => ({
      id: a.id,
      src: a.photo,
      title: a.title,
      date: a.year,
      size: a.width && a.height ? `${a.width}×${a.height} см` : null
    }))
  } catch (e) {
    console.error('Ошибка загрузки живописи', e)
  }
}

async function fetchGraphics() {
  try {
    const { data } = await axios.get(`${API_URL}/api/v1/art-items`, {
      params: { category: 2 }
    })
    graphicsItems.value = data.results.map(a => ({
      id: a.id,
      src: a.photo,
      title: a.title,
      date: a.year,
      format: a.width && a.height ? `${a.width}×${a.height} см` : null
    }))
  } catch (e) {
    console.error('Ошибка загрузки графики', e)
  }
}

async function fetchBooksHome() {
  try {
    const { data } = await axios.get(`${API_URL}/api/v1/books`)
    bookItems.value = data.results.map(b => ({
      id: b.id,
      src: b.photo,
      title: b.title,
      year: b.year
    }))
  } catch (e) {
    console.error('Ошибка загрузки книг', e)
  }
}


const contacts = [
  {
    title: 'Череповецкое Музейное Объединение',
    src: chermo,
    address: 'г. Череповец, Советский пр., 30 А',
